#!/usr/bin/env node
// Generate the LOCAL dev wrangler config for each Worker that calls another Worker.
//
// The problem: `apps/web`, `apps/api` and `apps/mcp` reach `apps/auth` and `apps/engine` over Cloudflare
// service bindings — 18 of them. Only two are committed, because Cloudflare rejects an UPLOAD whose service
// binding names a Worker that does not exist yet: committing all 18 would block a cold deploy, since a fresh
// environment brings the Workers up one at a time and `webhook-web` could not deploy before `webhook-auth`
// existed. So the deploy overlay injects them at deploy time, after the targets are live.
//
// That deploy-safety property must not be traded away for local convenience — but it left every one of those
// calls unexercisable locally. The shape that satisfies both is the one the deploy already uses: a
// GENERATED, GITIGNORED config. This writes `apps/<app>/wrangler.dev.jsonc`, which the app's `dev` script
// passes to wrangler with `-c`. Nothing new is committed, so a cold deploy is unaffected.
//
// `wrangler dev` resolves a service binding across SEPARATE dev sessions through its dev registry, keyed on
// the target's config `name` — so `pnpm dev` starting every app is what makes these bindings answerable.
//
// ⚠️ A declared binding whose target is NOT running still BOOTS the caller: the binding is present, and the
// call throws `Network connection lost` only when made. Readers that check structurally (`if (!env.X)
// degrade`) therefore start passing that check and then throw. Run the whole stack, not a subset.
//
// Run: node scripts/gen-wrangler-dev.mjs   (wired into `pnpm dev`)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { extractServices, mergeServices, SERVICE_BINDINGS } from "./wrangler-services.mjs";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Apps that call another Worker — exactly the keys of the shared table, never a second list. */
export const CALLING_APPS = Object.freeze(Object.keys(SERVICE_BINDINGS));

const BANNER =
  "// GENERATED by scripts/gen-wrangler-dev.mjs — do not edit, and do not commit (see .gitignore).\n" +
  "// This is apps/<app>/wrangler.jsonc plus the cross-Worker service bindings, which are not committed\n" +
  "// because Cloudflare would reject a cold deploy that named a Worker not yet live.\n";

/**
 * Build the dev config text for one app: its committed config with the service bindings merged in.
 *
 * Pure and exported so tests can drive it without touching the filesystem.
 */
export function devConfigFor(app, committedText) {
  const committed = extractServices(committedText);
  const merged = mergeServices(SERVICE_BINDINGS[app] ?? [], committed.entries);
  if (merged.length === 0) return null; // nothing to add — the app calls nobody
  const body = committed.entries.length > 0 ? committed.without : committedText;
  const brace = body.indexOf("{");
  if (brace < 0) throw new Error(`${app}: committed wrangler.jsonc has no opening brace`);
  const block = `  ${JSON.stringify("services")}: ${JSON.stringify(merged)}`;
  return BANNER + body.slice(0, brace + 1) + "\n" + block + "," + body.slice(brace + 1);
}

function run() {
  if (CALLING_APPS.length === 0) {
    console.error(
      "gen-wrangler-dev: the service-binding table is empty — refusing to pass vacuously.",
    );
    process.exit(1);
  }
  let written = 0;
  for (const app of CALLING_APPS) {
    const src = join(REPO, "apps", app, "wrangler.jsonc");
    const text = devConfigFor(app, readFileSync(src, "utf8"));
    if (text === null) continue;
    writeFileSync(join(REPO, "apps", app, "wrangler.dev.jsonc"), text);
    written++;
  }
  const total = CALLING_APPS.reduce((n, a) => n + SERVICE_BINDINGS[a].length, 0);
  console.log(`✅ wrote ${written} dev configs carrying ${total} service bindings`);
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  run();
}
